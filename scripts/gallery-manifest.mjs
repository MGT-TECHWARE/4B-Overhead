#!/usr/bin/env node
/**
 * Reads dimensions of every webp in src/assets/gallery and writes
 * src/assets/gallery/manifest.ts. Used by Work.tsx so each <img>
 * declares its real intrinsic width/height (CLS killer).
 *
 * Run after optimize-images.mjs whenever gallery photos change:
 *   node scripts/gallery-manifest.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const DIR = join(__dirname, '..', 'src/assets/gallery');
const OUT = join(DIR, 'manifest.ts');

function naturalKey(name) {
  const m = name.match(/(\d+)/);
  return m ? parseInt(m[1], 10) : 0;
}

async function main() {
  const entries = (await readdir(DIR))
    .filter(f => extname(f).toLowerCase() === '.webp')
    .sort((a, b) => naturalKey(a) - naturalKey(b));

  const records = [];
  for (const file of entries) {
    const buf = await readFile(join(DIR, file));
    const meta = await sharp(buf).metadata();
    if (meta.width && meta.height) {
      records.push({ file, w: meta.width, h: meta.height });
    }
  }

  const lines = [
    '/**',
    ' * AUTO-GENERATED by scripts/gallery-manifest.mjs — do not edit by hand.',
    ' * Maps gallery filename -> intrinsic dimensions so <img> tags can declare',
    ' * width/height and the browser reserves correct layout space (no CLS).',
    ' */',
    '',
    'export interface GalleryEntry { file: string; w: number; h: number }',
    '',
    'export const GALLERY: ReadonlyArray<GalleryEntry> = [',
    ...records.map(
      r => `  { file: ${JSON.stringify(r.file)}, w: ${r.w}, h: ${r.h} },`
    ),
    '];',
    ''
  ];

  await writeFile(OUT, lines.join('\n'), 'utf8');
  console.log(`wrote ${OUT} (${records.length} entries)`);
}

main().catch(err => {
  console.error('[gallery-manifest] failed:', err);
  process.exit(1);
});
